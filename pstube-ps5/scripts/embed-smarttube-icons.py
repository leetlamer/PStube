#!/usr/bin/env python3
"""Embed the pinned, unchanged PNG assets; provenance/licenses remain in assets/smarttube."""
from pathlib import Path
import hashlib,json
app=Path(__file__).resolve().parents[1]
folder=app/'assets/smarttube';manifest=json.loads((folder/'provenance.json').read_text())
output=['// Generated by scripts/embed-smarttube-icons.py. See assets/smarttube for licenses.','#pragma once','#include <cstddef>','#include <cstring>','namespace smarttube {','struct EmbeddedIcon {const char* name;const unsigned char* data;size_t size;};']
rows=[]
for index,item in enumerate(manifest['files']):
    data=(folder/item['file']).read_bytes();assert hashlib.sha256(data).hexdigest()==item['sha256']
    symbol='smartTubeIcon'+str(index)
    output.append('static const unsigned char '+symbol+'[]={'+','.join(str(v) for v in data)+'};')
    rows.append('{"'+Path(item['file']).stem+'",'+symbol+',sizeof('+symbol+')}')
output.append('static const EmbeddedIcon embeddedIcons[]={'+','.join(rows)+'};')
output.append('inline const EmbeddedIcon* embeddedIcon(const char* name) {for(const auto& icon:embeddedIcons) if(!strcmp(icon.name,name)) return &icon;return nullptr;}')
output.append('}')
(app/'src/generated/smarttube_icons.h').write_text('\n'.join(output)+'\n')
